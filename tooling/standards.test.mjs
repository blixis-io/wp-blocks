// Proves the standards tooling actually enforces what it claims (BWB-013): strict TypeScript, ESLint rules,
// Conventional Commits and the no-AI-attribution policy. Uses the locally installed tools.
import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { findAttribution } from '../commitlint.config.mjs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const run = (args, input) => spawnSync('pnpm', ['exec', ...args], { cwd: root, encoding: 'utf8', input });
const eslintStdin = (filename, code) => {
  const out = run(['eslint', '--format', 'json', '--stdin', '--stdin-filename', filename], code);
  return JSON.parse(out.stdout || '[]').flatMap((f) => f.messages.map((m) => m.ruleId));
};
const tmp = mkdtempSync(join(tmpdir(), 'blx-standards-'));
test.after(() => rmSync(tmp, { recursive: true, force: true }));

function tsc(file) {
  const project = join(tmp, `${Math.random().toString(36).slice(2)}.json`);
  writeFileSync(project, JSON.stringify({ extends: join(root, 'tsconfig.base.json'), files: [file] }));
  return run(['tsc', '-p', project]);
}
function eslint(file) {
  const out = run(['eslint', '--format', 'json', file]);
  const report = JSON.parse(out.stdout || '[]');
  return report.flatMap((f) => f.messages.map((m) => m.ruleId));
}

test('strict TypeScript accepts conforming code', () => {
  const r = tsc(join(root, 'tooling/fixtures/good/ok.ts'));
  assert.equal(r.status, 0, r.stdout + r.stderr);
});

test('strict TypeScript rejects implicit any', () => {
  const r = tsc(join(root, 'tooling/fixtures/bad/implicit-any.ts'));
  assert.notEqual(r.status, 0);
  assert.match(r.stdout, /TS7006/);
});

test('strict TypeScript rejects unchecked indexed access (noUncheckedIndexedAccess)', () => {
  const r = tsc(join(root, 'tooling/fixtures/bad/unchecked-index.ts'));
  assert.notEqual(r.status, 0);
  assert.match(r.stdout, /TS2322/);
});

test('ESLint passes conforming TypeScript', () => {
  assert.deepEqual(eslint(join(root, 'tooling/fixtures/good/ok.ts')), []);
});

test('ESLint rejects explicit any', () => {
  const rules = eslint(join(root, 'tooling/fixtures/bad/explicit-any.ts'));
  assert.ok(rules.includes('@typescript-eslint/no-explicit-any'), rules.join());
});

test('ESLint rejects @ts-ignore', () => {
  const rules = eslint(join(root, 'tooling/fixtures/bad/ts-ignore.ts'));
  assert.ok(rules.includes('@typescript-eslint/ban-ts-comment'), rules.join());
});

const lint = (message) => run(['commitlint'], message);

test('commitlint accepts Conventional Commits', () => {
  for (const m of [
    'feat(editor): add element inspector',
    'fix(renderer): escape image alt attributes',
    'docs: update roadmap',
    'feat(core)!: version document schema\n\nBREAKING CHANGE: migrate documents',
  ]) {
    const r = lint(m);
    assert.equal(r.status, 0, `${m}\n${r.stdout}`);
  }
});

test('commitlint rejects non-conventional headers', () => {
  for (const m of ['added stuff', 'feature: add x', 'feat(Editor): bad scope case', 'feat: ' + 'x'.repeat(110)]) {
    assert.notEqual(lint(m).status, 0, m);
  }
});

test('commitlint rejects AI attribution (GITFLOW policy)', () => {
  for (const m of [
    'feat: add x\n\nCo-Authored-By: Claude Sonnet <noreply@anthropic.com>',
    'feat: add x\n\nCo-authored-by: Codex <codex@openai.com>',
    'docs: add y\n\nGenerated with [Claude Code](https://claude.com/claude-code)',
    'docs: add y\n\n🤖 Generated by an assistant',
  ]) {
    const r = lint(m);
    assert.notEqual(r.status, 0, m);
    assert.match(r.stdout, /no-ai-attribution/, m);
  }
});

test('commitlint allows human co-authors and ordinary words', () => {
  const r = lint(
    'feat: add reviewer notes\n\nCo-authored-by: Jane Doe <jane@example.com>\n\nGenerated fixtures are deterministic.',
  );
  assert.equal(r.status, 0, r.stdout);
});

test('attribution rule: line-based edge cases', () => {
  const flagged = [
    'Assisted-by: Claude:claude-opus',
    'Generated-by: some tool',
    'Co-authored-by:\nClaude <noreply@anthropic.com>',
    'Co-authored-by: Helper <noreply@openai.com>',
    'Co-Authored-By: GPT-5 <x@example.com>',
    '— Claude',
    'Generated with Claude Code',
    'created using ChatGPT',
    'done 🤖',
  ];
  for (const m of flagged) assert.notEqual(findAttribution(`feat: x\n\n${m}`), null, m);
  const allowed = [
    'Co-authored-by: Jane Doe <jane@ai.org>',
    'Co-authored-by: dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>',
    'Generated fixtures are deterministic.',
    'Signed-off-by: Jane Doe <jane@example.com>',
    'Refs #12',
  ];
  for (const m of allowed) assert.equal(findAttribution(`feat: x\n\n${m}`), null, m);
});

test('attribution rule: pathological input stays fast (no quadratic backtracking)', () => {
  const start = Date.now();
  findAttribution('Generated with '.repeat(25000));
  findAttribution(('x'.repeat(1000) + '\n').repeat(300));
  assert.ok(Date.now() - start < 1000, `took ${Date.now() - start}ms`);
});

test('the commit-msg hook runs commitlint and blocks a bad message', () => {
  const file = join(tmp, 'msg.txt');
  writeFileSync(file, 'not conventional');
  const bad = spawnSync('sh', [join(root, '.husky/commit-msg'), file], { cwd: root, encoding: 'utf8' });
  assert.notEqual(bad.status, 0);
  writeFileSync(file, 'chore: valid message');
  const good = spawnSync('sh', [join(root, '.husky/commit-msg'), file], { cwd: root, encoding: 'utf8' });
  assert.equal(good.status, 0, good.stdout + good.stderr);
});

test('ESLint blocks React, dnd-kit and GSAP imports in framework-free packages', () => {
  for (const mod of ['react', 'react-dom/client', 'zustand', '@dnd-kit/core', 'tailwindcss', 'gsap']) {
    const rules = eslintStdin('packages/core/src/example.mjs', `import x from '${mod}';\nexport default x;\n`);
    assert.ok(rules.includes('no-restricted-imports'), `${mod}: ${rules.join()}`);
  }
  for (const pkg of ['wordpress/theme/src/a.mjs', 'wordpress/plus/src/a.mjs']) {
    assert.ok(eslintStdin(pkg, "import x from 'react';\nexport default x;\n").includes('no-restricted-imports'), pkg);
  }
});

test('ESLint allows React in editor-ui and blocks GSAP everywhere', () => {
  assert.ok(
    !eslintStdin('packages/editor-ui/src/a.mjs', "import x from 'react';\nexport default x;\n").includes(
      'no-restricted-imports',
    ),
  );
  assert.ok(
    eslintStdin('apps/editor/src/a.mjs', "import x from 'gsap';\nexport default x;\n").includes(
      'no-restricted-imports',
    ),
  );
});

test('Prettier flags badly formatted code', () => {
  const file = join(tmp, 'ugly.mjs');
  writeFileSync(file, 'export const a  =   {b:1,\n c:2}\n');
  const r = run(['prettier', '--config', join(root, '.prettierrc.json'), '--check', file]);
  assert.notEqual(r.status, 0);
});

test('ESLint keeps Node APIs out of packages/core source but allows them in its tests and scripts', () => {
  const code = "import { readFileSync } from 'node:fs';\nexport default readFileSync;\n";
  assert.ok(eslintStdin('packages/core/src/example.mjs', code).includes('no-restricted-imports'));
  for (const bare of ['fs', 'path', 'crypto', 'fs/promises', 'child_process']) {
    assert.ok(
      eslintStdin('packages/core/src/example.mjs', `import x from '${bare}';\nexport default x;\n`).includes(
        'no-restricted-imports',
      ),
      bare,
    );
  }
  assert.ok(!eslintStdin('packages/core/src/example.test.mjs', code).includes('no-restricted-imports'));
  assert.ok(!eslintStdin('packages/core/scripts/example.mjs', code).includes('no-restricted-imports'));
});
